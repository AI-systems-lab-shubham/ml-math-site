// Measures every lazy widget and writes its static placeholder and reserved height.
// Usage: node tools/measure-widgets.mjs [--write] [--pages m00-slope,m01-vectors] [--widths 375,900,1280]
// Without --write it only reports. Pages come from data/course.json (one per built concept) and are measured in parallel.
// --pages and --widths narrow a checkpoint run (they cannot be combined with --write). Run it after adding or changing a widget; tests/e2e/widgets-lazy.mjs fails if a placeholder is stale.
// For each widget it mounts the real thing, then sweeps the viewport width. At each width it records the widget's own
// width and the height of everything below the drawing (controls + readout). That height is a step function of the
// widget's width (the controls wrap), written as @container rules to assets/css/widget-reserve.css.
// The title and description are copied into the page as the placeholder's visible text.
import fs from "node:fs";
import path from "node:path";
import { requirePlaywright, serveStatic, siteRoot } from "./lib/playwright.mjs";

const arg = (name) => (process.argv.includes(name) ? process.argv[process.argv.indexOf(name) + 1] : null);
const WRITE = process.argv.includes("--write");
const course = JSON.parse(fs.readFileSync(path.join(siteRoot, "data/course.json"), "utf8"));
const only = arg("--pages")?.split(",") ?? null;       // concept ids; default is every built concept page in course.json
const WIDTHS = arg("--widths")?.split(",").map(Number) ?? null;   // sample only these widths (checkpoint runs; cannot --write)
if (WRITE && (WIDTHS || only)) { console.error("--write needs the full sweep: do not combine it with --pages or --widths"); process.exit(1); }
const PAGES = course.modules.flatMap((m) => m.concepts.filter((c) => m.status === "built" && c.status === "built" && (!only || only.includes(c.id))).map((c) => c.path));
const STEP = 1; // 1px: the controls wrap at exact widths, and a coarser sweep leaves a window where the reserve is one line off
const JOBS = 4; // pages measured at the same time
const esc = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const pw = await requirePlaywright("measure-widgets");
const server = await serveStatic();
const browser = await pw.chromium.launch();
let failed = false;

async function measure(page) {
  const ctx = await browser.newContext({ viewport: { width: 1500, height: 900 } });
  const pg = await ctx.newPage();
  await pg.goto(`${server.base}${page}`);
  await pg.evaluate(async () => { (await import("/assets/js/widgets.mjs")).mountAllLazy(); });
  await pg.waitForFunction(() => [...document.querySelectorAll("[data-widget]")].every((h) => h.dataset.lazy === "mounted"));
  await pg.evaluate(() => document.fonts.ready);
  const info = new Map(); // name -> { title, desc, samples: [[hostWidth, reserve]] }
  const widths = [];
  if (WIDTHS) widths.push(...WIDTHS); else for (let w = 1500; w >= 320; w -= STEP) widths.push(w);
  for (const width of widths) {
    await pg.setViewportSize({ width, height: 900 });
    await pg.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))));
    const rows = await pg.evaluate(() => [...document.querySelectorAll("[data-widget]")].map((h) => {
      const fig = h.querySelector(".widget-draw");
      const last = h.querySelector(".readout") ?? h.querySelector(".widget-controls");
      return { name: h.dataset.widget, title: h.querySelector(".widget-title").textContent, desc: fig.getAttribute("aria-label"),
        hostWidth: h.getBoundingClientRect().width, reserve: last.getBoundingClientRect().bottom - fig.getBoundingClientRect().bottom };
    }));
    for (const r of rows) {
      const e = info.get(r.name) ?? { title: r.title, desc: r.desc, samples: [] };
      e.samples.push([Math.floor(r.hostWidth), Math.ceil(r.reserve)]);
      info.set(r.name, e);
    }
  }
  await ctx.close();
  return info;
}

// Pages are measured in parallel; the results are used in course order so the generated CSS does not depend on timing.
const results = new Array(PAGES.length);
let nextJob = 0;
await Promise.all(Array.from({ length: Math.min(JOBS, PAGES.length) }, async () => {
  while (nextJob < PAGES.length) { const i = nextJob++; results[i] = await measure(PAGES[i]); }
}));

const css = ["/* Generated by tools/measure-widgets.mjs. Do not edit by hand. Per-widget reserved height below the drawing, by widget width. */"];
const seen = new Set();
PAGES.forEach((page, i) => {
  const info = results[i];
  const file = path.join(siteRoot, page, "index.html");
  let html = fs.readFileSync(file, "utf8");
  for (const [name, e] of info) {
    if (seen.has(name)) { console.error(`duplicate widget name ${name}`); failed = true; }
    seen.add(name);
    // Run-length compress: widest first in the sweep, so sort ascending and emit a rule where the height changes.
    const samples = [...e.samples].sort((a, b) => a[0] - b[0]);
    const rules = [];
    let prev = null;
    for (const [w, h] of samples) if (h !== prev) { rules.push([w, h]); prev = h; }
    const [, base] = rules[0];
    css.push(`[data-widget="${name}"] .widget-reserve { min-height: ${base}px; }`);
    for (const [w, h] of rules.slice(1)) css.push(`@container (min-width: ${w}px) { [data-widget="${name}"] .widget-reserve { min-height: ${h}px; } }`);
    console.log(`${page}${name}: ${WIDTHS ? samples.map(([w, h]) => `${w}px→${h}`).join(" ") : `${rules.length} bands, ${Math.min(...samples.map((s) => s[1]))} to ${Math.max(...samples.map((s) => s[1]))}px`}`);
    const open = `<div data-widget="${name}"`;
    const start = html.indexOf(open);
    if (start < 0) { console.error(`  no host for ${name}`); failed = true; continue; }
    const tagEnd = html.indexOf(">", start) + 1;
    const endMark = "</div><!-- /widget -->";
    const end = html.startsWith("</div>", tagEnd) ? tagEnd + 6 : html.indexOf(endMark, tagEnd) + endMark.length;
    const block = `<div data-widget="${name}">
        <div class="widget widget-placeholder">
          <p class="widget-title">${esc(e.title)}</p>
          <figure class="widget-draw"><figcaption class="widget-desc">${esc(e.desc)}</figcaption></figure>
          <div class="widget-reserve" aria-hidden="true"></div>
        </div>
      ${endMark}`;
    if (WRITE) html = html.slice(0, start) + block + html.slice(end);
  }
  if (WRITE) fs.writeFileSync(file, html);
});
if (WRITE) fs.writeFileSync(path.join(siteRoot, "assets/css/widget-reserve.css"), `${css.join("\n")}\n`);
await browser.close();
await server.close();
process.exit(failed ? 1 : 0);
